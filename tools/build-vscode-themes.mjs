#!/usr/bin/env node
// Builds Herdr themes and our syntax colors from the VS Code app bundle's own theme files:
//   node tools/build-vscode-themes.mjs ["/Applications/Visual Studio Code - Insiders.app"]
// Writes themes/herdr-vscode-{dark-plus,dark-modern,light-modern}.json and shared/vscode-syntax-core.js.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { mergeThemeChain, herdrTheme, syntaxFromTokens, parseAnsiDefaults } from "./vscode-core.mjs";

const APPS = ["/Applications/Visual Studio Code - Insiders.app", "/Applications/Visual Studio Code.app"];
const THEMES = [
  { name: "herdr-vscode-dark-plus", file: "dark_plus.json", type: "dark" },
  { name: "herdr-vscode-dark-modern", file: "dark_modern.json", type: "dark" },
  { name: "herdr-vscode-light-modern", file: "light_modern.json", type: "light" },
];

const repoRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const app = process.argv[2] ?? APPS.find((candidate) => fs.existsSync(candidate));
if (!app) {
  console.error("build-vscode-themes: no VS Code app found; pass its .app path");
  process.exit(1);
}
const resources = path.join(app, "Contents/Resources/app");
const themesDir = path.join(resources, "extensions/theme-defaults/themes");

function loadChain(file) {
  const theme = JSON.parse(fs.readFileSync(path.join(themesDir, file), "utf8"));
  return theme.include ? [...loadChain(path.basename(theme.include)), theme] : [theme];
}

const ansi = parseAnsiDefaults(fs.readFileSync(path.join(resources, "out/vs/workbench/workbench.desktop.main.js"), "utf8"));
if (!ansi) {
  console.error("build-vscode-themes: terminal ANSI defaults not found in the VS Code bundle");
  process.exit(1);
}

const syntax = {};
for (const { name, file, type } of THEMES) {
  const merged = mergeThemeChain(loadChain(file));
  const theme = herdrTheme(merged.colors, ansi[type], type);
  fs.writeFileSync(path.join(repoRoot, "themes", `${name}.json`), `${JSON.stringify(theme, null, 2)}\n`);
  syntax[theme.background] = syntaxFromTokens(merged.tokenColors);
  console.log(`build-vscode-themes: themes/${name}.json`);
}

const core = `// Generated by tools/build-vscode-themes.mjs from VS Code's theme files: do not edit.
// Token colors per Herdr theme background, for the herdr-vscode-* themes.
export const VSCODE_SYNTAX = ${JSON.stringify(syntax, null, 2)};
`;
fs.writeFileSync(path.join(repoRoot, "shared/vscode-syntax-core.js"), core);
console.log("build-vscode-themes: shared/vscode-syntax-core.js");
